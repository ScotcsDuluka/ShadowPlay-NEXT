'use strict';
// Static, read-only scan of Express route literals. Does not execute the app.
// Route count is source declarations; routing order or runtime success is NOT established.
const fs = require('fs'), path = require('path');
const project = path.resolve(__dirname, '../../Project/Overlay On-Screen Control/NVIDIA NodeAPI');
const dest = __dirname;
const candidates = [
  ...fs.readdirSync(project).filter(n => n.endsWith('.js')).map(n=>path.join(project,n)),
  ...fs.readdirSync(path.join(project,'shims')).filter(n => n.endsWith('.js')).map(n=>path.join(project,'shims',n))
];
const all = [], summary = [];
function lineNumber(text,index) {
  let count=1;
  for(let i=0;i<index;i++) if(text.charCodeAt(i)===10) count++;
  return count;
}
for(const file of candidates) {
  const txt=fs.readFileSync(file,'utf8');
  const re=/\bapp\.(get|post|put|patch|delete|all)\(\s*(['"`])(\/[^'"`\r\n]+)\2/g;
  let match, count=0;
  while((match=re.exec(txt))) {
    const route=match[3].replace(/\s+/g,' ');
    if(route.length>240) continue;
    all.push({method:match[1].toUpperCase(),path:route,source:path.relative(project,file).replace(/\\/g,'/'),line:lineNumber(txt,match.index)});
    count++;
  }
  if(count) summary.push({file:path.relative(project,file).replace(/\\/g,'/'),count});
}
const pathKey=x=>x.method+' '+x.path;
const groups=new Map();
for(const row of all) {
  const key=pathKey(row);
  if(!groups.has(key)) groups.set(key,[]);
  groups.get(key).push(row);
}
const overlaps=Array.from(groups.entries()).filter(([_,rows])=>rows.length>1);
summary.sort((a,b)=>b.count-a.count);
const inventory=[
  '# OSC / NodeAPI — Static Express endpoint inventory',
  '',
  'Generated by read-only parser: '+new Date().toISOString()+'. Source routes only, **NOT real-time availability**.',
  'Scans explicit `app.get/post/put/patch/delete/all` literals in NodeAPI top-level *.js and shims/*.js; does not include dynamic route registration, other upstream services, CEF native commands, or Socket.IO.',
  '',
  '**Route declarations discovered:** '+all.length+' across '+summary.length+' source files. **Repeated method/path keys:** '+overlaps.length+'.',
  '',
  '## Modules',
  '',
  '| File | Explicit routes |',
  '|---|---:|',
  ...summary.map(x=>'| `'+x.file+'` | '+x.count+' |'),
  '',
  '## Repeated method/path declarations (review Express precedence)',
  '',
  ...(overlaps.length ? overlaps.map(([key,rows])=>'- `'+key+'` — '+rows.map(x=>'`'+x.source+':'+x.line+'`').join('; ')) : ['None found among extracted literals.']),
  '',
  '## All extracted method/path declarations',
  '',
  '| Method | Path | Source | Line |',
  '|---|---|---|---:|',
  ...all.sort((a,b)=>a.path.localeCompare(b.path)||a.method.localeCompare(b.method)).map(x=>'| '+x.method+' | `'+x.path.replace(/\|/g,'\\|')+'` | `'+x.source+'` | '+x.line+' |'),
  '',
  '## Interpretation',
  'A route can be a legacy/native-addon facade, compatibility stub, source-only route, or fully wired endpoint. Do not conclude success from this table. Validate method, active Build, Host/Origin policy, upstream worker truth and final effects separately.'
].join('\n');
const outfile=path.join(dest,'OSC-BACKEND-ROUTE-INVENTORY-20261025.md');
fs.writeFileSync(outfile, inventory,'utf8');
console.log(JSON.stringify({total:all.length,files:summary.length,repeated:overlaps.length,top:summary.slice(0,18),overlaps:overlaps.slice(0,16).map(([key,rows])=>({key,source:rows.map(x=>x.source+':'+x.line)})),outfile},null,2));
